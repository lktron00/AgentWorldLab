"""Offline verification of model receipts, every decision and real-engine frames."""
from collections import Counter
from decimal import Decimal
import json
import hashlib
from pathlib import Path
import sqlite3
import sys
from .audit import AuditError, audit_ledger
from .common import read_json, write_json
from .costs import amount, usd
from .experiment import fingerprint, world_fingerprint
from .incident import observation, status_result
from .pilot_catalog import journal
from .society_contract import validate_batch


def audit_pilot(directory):
    directory = Path(directory)
    report = read_json(directory / 'report.json')
    accounting = audit_ledger(directory / 'costs.jsonl')
    if accounting['journal_truncated'] or accounting['warnings'] or accounting['summary']['unresolved_calls']:
        raise AuditError('The cost journal requires reconciliation before verifying completion')
    # Independently replay the live budget gate, including simultaneous reservations.
    pending, spent, peak = {}, Decimal(0), Decimal(0)
    requests, responses = {}, {}
    budget = amount(accounting['summary']['budget_usd'])
    for line in (directory / 'costs.jsonl').read_text().splitlines():
        event = json.loads(line)
        if event['event'] == 'reserved':
            pending[event['call_id']] = amount(event['reserved_usd'])
            requests[event['call_id']] = event
        elif event['event'] == 'response':
            responses[event['call_id']] = event['response']
        elif event['event'] == 'charged':
            cost = amount(event['estimated_cost_usd'])
            if cost > pending[event['call_id']]:
                raise AuditError('A reported charge exceeded its reserved maximum')
            pending.pop(event['call_id'])
            spent += cost
        exposure = spent + sum(pending.values(), Decimal(0))
        peak = max(peak, exposure)
        if exposure > budget:
            raise AuditError('Combined receipts and in-flight reservations exceeded the shared budget')
    receipts = {r['call_id']: r for r in accounting['receipts']}
    decisions, batches = {}, {}
    for event in journal(directory / 'decisions.jsonl'):
        if event['event'] == 'decision':
            key = event['seed'], event['branch'], event['step'], event['actor']
            if key in decisions:
                raise AuditError('Duplicate account decision for a tick')
            if event['observation_sha256'] != fingerprint(event['observation']):
                raise AuditError('Observation hash mismatch')
            receipt = receipts.get(event['call_id'])
            if receipt is None or any(receipt[k] != event[k] for k in ('response_id', 'model', 'usage', 'estimated_cost_usd')):
                raise AuditError('A decision has no matching provider usage receipt')
            if not (event['model'] == 'gpt-6-luna' or event['model'].startswith('gpt-6-luna-')):
                raise AuditError('A decision was generated by an unexpected model')
            request = requests[event['call_id']]['request']
            if json.loads(request['input'][0]['content']) != event['observation']:
                raise AuditError('The recorded observation differs from the actual provider request')
            if report.get('instructions') is not None and request['instructions'] != report['instructions']:
                raise AuditError('Model instructions differ from the recorded experimental design')
            if any(requests[event['call_id']].get(field) != event.get(field) for field in ('seed', 'branch', 'actor', 'step')):
                raise AuditError('A receipt was assigned to a different account or tick')
            response = responses[event['call_id']]
            calls = [item for item in response.get('output', []) if item.get('type') == 'function_call']
            if response.get('status') != 'completed' or len(calls) != 1 or calls[0].get('name') != 'choose_action':
                raise AuditError('A decision does not have a complete model function call')
            proposal = json.loads(calls[0]['arguments'])
            if proposal != {**event['action'], 'reason': event['reason'], 'belief_loss': event['belief_loss']}:
                raise AuditError('The saved decision differs from what the provider actually returned')
            if event['usage']['input_tokens'] > requests[event['call_id']]['input_tokens_counted']:
                raise AuditError('Reported input exceeded the exact pre-generation count')
            decisions[key] = event
        elif event['event'] == 'applied_batch':
            key = event['seed'], event['branch'], event['step']
            if key in batches:
                raise AuditError('Duplicate committed batch')
            batches[key] = event
    used = [d['call_id'] for d in decisions.values()]
    if len(set(used)) != len(used) or set(used) != set(receipts):
        raise AuditError('Every paid call must correspond to exactly one valid decision')
    config = report['config']
    expected = config['population'] * config['steps'] * report['requested_pairs'] * 2
    if len(decisions) != expected or len(batches) * config['population'] != expected or len(report['experiments']) != report['requested_pairs']:
        raise AuditError('The pilot does not contain its complete planned scope')
    frames_verified, events_verified, databases_verified = 0, 0, 0
    for pair in report['experiments']:
        if pair['status'] != 'completed' or set(pair['branches']) != {'generic', 'diagnostic'}:
            raise AuditError('Incomplete pair')
        for branch_name, branch in pair['branches'].items():
            run = directory / 'engine/runs' / branch['run_id']
            frames = [read_json(run / 'frames' / f'{step:04d}.json') for step in range(config['steps'] + 1)]
            hashes = [world_fingerprint(f) for f in frames]
            if hashes != branch['world_sha256'] or hashes[0] != pair['initial_world_sha256']:
                raise AuditError('A saved engine world differs from the reported trajectory')
            frames_verified += len(frames)
            with sqlite3.connect(f'file:{run / "oasis.sqlite"}?mode=ro', uri=True) as db:
                actual = db.execute('SELECT p.post_id,p.user_id,p.original_post_id,p.created_at,p.num_shares,r.content '
                                    'FROM post p JOIN post r ON r.post_id=COALESCE(p.original_post_id,p.post_id) ORDER BY p.post_id').fetchall()
                final = frames[-1]['world']
                fields = ('post_id', 'user_id', 'original_post_id', 'created_at', 'num_shares', 'content')
                expected_posts = [tuple(p[k] for k in fields) for p in final['posts']]
                expected_nodes = [(n['id'], n['name']) for n in final['nodes']]
                if (actual != expected_posts or db.execute('SELECT user_id,name FROM user ORDER BY user_id').fetchall() != expected_nodes
                        or [list(e) for e in db.execute('SELECT follower_id,followee_id FROM follow ORDER BY follower_id,followee_id')] != final['edges']):
                    raise AuditError('OASIS database disagrees with its final frame')
            databases_verified += 1
            events = [json.loads(line) for line in (run / 'events.jsonl').read_text().splitlines()]
            if len(events) != config['population'] * config['steps']:
                raise AuditError('Missing applied account actions in engine journal')
            memory = {str(i): [] for i in range(1, config['population'] + 1)}
            checks = {str(i): [] for i in range(1, config['population'] + 1)}
            count = Counter()
            for step in range(config['steps']):
                tick = [decisions[pair['seed'], branch_name, step, i] for i in range(1, config['population'] + 1)]
                batch = batches[pair['seed'], branch_name, step]
                if batch['decision_ids'] != [d['decision_id'] for d in tick] or batch['world_sha256'] != hashes[step + 1]:
                    raise AuditError('Applied batch does not match the decisions or resulting engine world')
                validate_batch(frames[step], [{'actor': d['actor'], 'action': d['action']} for d in tick], step)
                for d in tick:
                    key = str(d['actor'])
                    expected_view = observation(frames[step], d['actor'], pair['profiles'][key], memory[key], checks[key])
                    if expected_view != d['observation']:
                        raise AuditError('A model did not receive exactly its reconstructed scoped view')
                    event = events[step * config['population'] + d['actor'] - 1]
                    if event['actor'] != d['actor'] or event['action'] != d['action'] or event['step'] != step + 1:
                        raise AuditError('AgentSociety/OASIS applied something other than the model decision')
                    count.update([d['action']['kind']])
                    events_verified += 1
                    memory[key].append({'step': step, 'action': d['action'], 'reason': d['reason'], 'belief_loss': d['belief_loss']})
                    if d['action']['kind'] == 'inspect_status':
                        checks[key].append({'requested_at_step': step, 'result': status_result(branch_name, step)})
            if dict(count) != branch['action_counts']:
                raise AuditError('Reported action counts differ from the applied decisions')
    result = {'verified': True, 'basis': 'Offline reconstruction; no API calls', 'scope': {
        'pairs': len(report['experiments']), 'worlds': databases_verified, 'active_accounts_per_world': config['population'],
        'model_decisions': len(decisions), 'applied_actions': events_verified, 'engine_frames': frames_verified,
        'distinct_provider_responses': len({r['response_id'] for r in receipts.values()})},
        'cost': accounting['summary'], 'peak_committed_plus_reserved_usd': usd(peak),
        'auditor_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        'checks': ['one Luna receipt per account per turn', 'shared budget including concurrent reservations',
                   'every observation reconstructed without global state', 'prompts and decisions match original provider requests/responses', 'identical paired initial worlds',
                   'every engine action equals its model proposal', 'OASIS databases and complete frame hashes']}
    return result


def main():
    directory = Path(sys.argv[1]).resolve()
    result = audit_pilot(directory)
    write_json(directory / 'audit.json', result)
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
